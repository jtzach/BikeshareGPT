from __future__ import annotations

from pathlib import Path
from typing import Any, Dict

from bikesharegpt.utils.io import ensure_dir, read_json, atomic_write_text


def _latex_escape(s: str) -> str:
    return (
        s.replace("\\", "\\textbackslash{}")
        .replace("_", "\\_")
        .replace("%", "\\%")
        .replace("&", "\\&")
        .replace("#", "\\#")
        .replace("{", "\\{")
        .replace("}", "\\}")
    )


def export_paper_artifacts(run_dir: str | Path) -> Path:
    """Create small LaTeX fragments to directly include in the ACL paper."""
    run_dir = Path(run_dir)
    summary_path = run_dir / "predictions" / "summary.json"
    if not summary_path.exists():
        raise FileNotFoundError(f"Missing {summary_path}")

    summary = read_json(summary_path)
    out = ensure_dir(run_dir / "paper_artifacts")

    # Accuracy table
    rows = summary.get("by_category", {})
    cats = sorted(rows.keys())
    lines = []
    lines.append("% Auto-generated by BikeshareGPT\n")
    lines.append("\\begin{table}[t]\n\\centering\n\\small\n")
    lines.append("\\begin{tabular}{lrrr}\n\\toprule\n")
    lines.append("Category & N & Accuracy & Exec. success\\\\\n\\midrule\n")
    for c in cats:
        r = rows[c]
        lines.append(f"{_latex_escape(c)} & {r['n']} & {r['accuracy']:.3f} & {r['exec_success_rate']:.3f}\\\\\n")
    lines.append("\\bottomrule\n\\end{tabular}\n")
    lines.append("\\caption{Benchmark results by category. Accuracy is exact-match or tolerance-based depending on the task grader.}\n")
    lines.append("\\label{tab:results_by_category}\n")
    lines.append("\\end{table}\n")
    atomic_write_text(out / "table_results.tex", "".join(lines))

    # Token/time summary (very lightweight)
    lines = []
    lines.append("% Auto-generated by BikeshareGPT\n")
    lines.append("\\begin{table}[t]\n\\centering\n\\small\n")
    lines.append("\\begin{tabular}{lrr}\n\\toprule\n")
    lines.append("Category & Total tokens & Total time (s)\\\\\n\\midrule\n")
    for c in cats:
        r = rows[c]
        lines.append(f"{_latex_escape(c)} & {int(r.get('total_tokens',0))} & {r.get('total_wall_time_s',0):.1f}\\\\\n")
    lines.append("\\bottomrule\n\\end{tabular}\n")
    lines.append("\\caption{Compute budget summary for the benchmark run.}\n")
    lines.append("\\label{tab:cost}\n")
    lines.append("\\end{table}\n")
    atomic_write_text(out / "table_cost.tex", "".join(lines))

    # A short macro with the run name (optional convenience)
    atomic_write_text(out / "run_id.tex", f"% Auto-generated\n\\newcommand{{\\bikesharegptrunid}}{{{_latex_escape(summary.get('run',''))}}}\n")

    return out


def export_suite_artifacts(suite_dir: str | Path) -> Path:
    """Create LaTeX fragments for a multi-model benchmark suite."""
    suite_dir = Path(suite_dir)
    suite_summary_path = suite_dir / "suite_summary.json"
    if not suite_summary_path.exists():
        raise FileNotFoundError(f"Missing {suite_summary_path}")

    suite_summary = read_json(suite_summary_path)
    out = ensure_dir(suite_dir / "paper_artifacts")
    models = suite_summary.get("models", [])

    # Overall comparison table
    lines = []
    lines.append("% Auto-generated by BikeshareGPT\n")
    lines.append("\\begin{table*}[t]\n\\centering\n\\small\n")
    lines.append("\\begin{tabular}{llrrrrr}\n\\toprule\n")
    lines.append("Model & Size & Sem. & Ret. & Syn. & Overall & Exec. success\\\\\n\\midrule\n")
    for m in models:
        bc = m.get("by_category", {})
        sem = bc.get("semantics", {}).get("accuracy", 0.0)
        ret = bc.get("retrieval", {}).get("accuracy", 0.0)
        syn = bc.get("synthesis", {}).get("accuracy", 0.0)
        overall = m.get("overall", {}).get("accuracy", 0.0)
        exec_rate = m.get("overall", {}).get("exec_success_rate", 0.0)
        lines.append(
            f"{_latex_escape(m.get('model_label', ''))} & "
            f"{_latex_escape(m.get('size_label', '-') or '-')} & "
            f"{sem:.3f} & {ret:.3f} & {syn:.3f} & {overall:.3f} & {exec_rate:.3f}\\\\\n"
        )
    lines.append("\\bottomrule\n\\end{tabular}\n")
    lines.append(
        "\\caption{Model-suite comparison on the packaged GBFS benchmark. Sem., Ret., and Syn. denote the semantics, retrieval, and synthesis tracks.}\n"
    )
    lines.append("\\label{tab:model_suite}\n")
    lines.append("\\end{table*}\n")
    atomic_write_text(out / "table_model_comparison.tex", "".join(lines))

    # Budget comparison table
    lines = []
    lines.append("% Auto-generated by BikeshareGPT\n")
    lines.append("\\begin{table}[t]\n\\centering\n\\small\n")
    lines.append("\\begin{tabular}{lrr}\n\\toprule\n")
    lines.append("Model & Total tokens & Total time (s)\\\\\n\\midrule\n")
    for m in models:
        overall = m.get("overall", {})
        lines.append(
            f"{_latex_escape(m.get('model_label', ''))} & "
            f"{int(overall.get('total_tokens', 0))} & {overall.get('total_wall_time_s', 0):.1f}\\\\\n"
        )
    lines.append("\\bottomrule\n\\end{tabular}\n")
    lines.append("\\caption{Model-suite compute budget summary.}\n")
    lines.append("\\label{tab:model_suite_cost}\n")
    lines.append("\\end{table}\n")
    atomic_write_text(out / "table_model_cost.tex", "".join(lines))

    return out
